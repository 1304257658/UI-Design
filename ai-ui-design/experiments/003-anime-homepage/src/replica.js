// Adaptation layer only. The visual runtime in public/assets/js belongs to Anime.js.
// Keep the original DOM and section geometry: scroll positions drive the 3D film.
window.paths = {
  'github-sponsors': '/sponsors/github-sponsors',
  'platinum-sponsors': '/sponsors/platinum-sponsors',
  'silver-sponsors': '/sponsors/silver-sponsors',
};

// Capture before the upstream custom element's submit handler: this replica never
// subscribes a visitor, stores an email, or calls the author's newsletter backend.
document.addEventListener('submit', event => {
  if (!event.target.closest('email-signup')) return;
  event.preventDefault();
  event.stopImmediatePropagation();
  const form = event.target;
  form.querySelector('.email-signup-fields')?.classList.remove('is-active');
  const message = form.querySelector('.email-signup-success');
  message?.classList.add('is-active');
  message?.setAttribute('role', 'status');
}, true);

document.querySelector('input[type="email"]')?.setAttribute('aria-label', 'Email address — local demo');

async function startReplica() {
try {
  // Kept as a public module tree, with original chunk boundaries and license banners.
  // This avoids mixing Three.js versions or re-bundling Draco's worker bootstrap.
  await new Promise((resolve, reject) => {
    const script = document.createElement('script');
    script.type = 'module';
    script.src = '/assets/js/home.js';
    script.onload = resolve;
    script.onerror = reject;
    document.body.append(script);
  });
  // These anchors are generated by the visual runtime, so label after it loads.
  for (const anchor of document.querySelectorAll('a.scroll-button')) {
    const target = document.querySelector(anchor.getAttribute('href'));
    anchor.setAttribute('aria-label', target?.querySelector('h2')?.textContent.trim() || anchor.hash.slice(1));
  }
} catch (error) {
  console.error('Local visual runtime could not start:', error);
  const message = document.createElement('p');
  message.setAttribute('role', 'alert');
  message.textContent = 'Preview resources could not load. Reload this page or check the local server.';
  Object.assign(message.style, {position:'fixed',bottom:'16px',left:'16px',zIndex:'9999',background:'#252423',padding:'16px',color:'#f6f4f2'});
  document.body.append(message);
}
}
startReplica();
